"""Write docs/progress_report/results.tex (LaTeX macros) from the metrics of run finetune_v1_20261123.

Standard library only, so it runs locally after `rsync`ing outputs/runs/ back from the server.
Missing results fall back to the base-model numbers (marked in the generated file) so the report always compiles.

Usage: python3 scripts/make_report_results.py --run outputs/runs/finetune_v1_20261123 --out docs/progress_report/results.tex
"""

import argparse
import json
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="outputs/runs/finetune_v1_20261123")
    ap.add_argument("--ce-train", default="data/train/ce_train.json")
    ap.add_argument("--out", default="docs/progress_report/results.tex")
    args = ap.parse_args()
    run = Path(args.run)
    base = load(run / "eval_base/metrics/results.json")
    ft = load(run / "eval_ft/metrics/results.json")
    ans = load(run / "eval_answers/metrics/metrics.json")
    tt = load(run / "eval_timetravel/metrics/timetravel.json")
    ce = load(args.ce_train)
    notes = []
    if ft is None:
        notes.append("eval_ft missing: fine-tuned numbers fall back to base")

    def M(name, val):
        return f"\\newcommand{{\\{name}}}{{{val}}}"

    lines = ["% generated by scripts/make_report_results.py -- do not edit by hand"]
    lines += [f"% NOTE: {n}" for n in notes]
    b_ret, f_ret = base["retrieval_only_test"], (ft or base)["retrieval_only_test"]
    bv, fv = base["variants"], (ft or base)["variants"]
    lines += [M("ResZsMrr", f3(b_ret["MRR@10"])), M("ResZsRten", f3(b_ret["R@10"])),
              M("ResZsCeMrr", f3(bv["retriever + re-ranker"]["MRR@10"])), M("ResZsCeRten", f3(bv["retriever + re-ranker"]["R@10"])),
              M("ResFtMrr", f3(f_ret["MRR@10"])), M("ResFtRten", f3(f_ret["R@10"])),
              M("ResFtCeMrr", f3(fv["retriever + re-ranker"]["MRR@10"])), M("ResFtCeRten", f3(fv["retriever + re-ranker"]["R@10"]))]
    no, yes = fv["retriever + re-ranker"], fv["full (graph + time)"]
    lines += [M("ResStaleNoTime", f3(no["Stale@10"])), M("ResStaleTime", f3(yes["Stale@10"])),
              M("ResTmrrNoTime", f3(no["T_MRR@10_cur"])), M("ResTmrrTime", f3(yes["T_MRR@10_cur"])),
              M("ResThitNoTime", f3(no["T_Hit@10_cur"])), M("ResThitTime", f3(yes["T_Hit@10_cur"])),
              M("ResNTemporal", f"{(ft or base)['n_test_temporal']:,}")]
    b = (ft or base)["best_val"]
    lines.append(M("ResWeights", f"$\\beta={b['beta']:g}$, $\\gamma={b['gamma']:g}$, $\\mu={b['mu']:g}$"))
    lines.append(M("ResCePairs", f"{ce['rows'] * 8:,}" if ce else "--"))

    labels = [("retriever + re-ranker", "retriever + re-ranker (no graph, no time)"),
              ("+ graph (beta, mu)", "\\quad + graph (PageRank, propagation)"),
              ("+ time (gamma, injection)", "\\quad + time (stale penalty, successor injection)"),
              ("full (graph + time)", "\\quad \\textbf{full (graph + time)}"),
              ("full - successor injection", "\\quad full $-$ successor injection"),
              ("full - explicit references", "\\quad full $-$ explicit references (similarity only)"),
              ("full, amends edges only", "\\quad full, amends edges only"),
              ("full, replaces/repeals only", "\\quad full, replaces / repeals edges only")]
    rows = []
    for key, lab in labels:
        v = fv.get(key)
        if v:
            rows.append(f"{lab} & {f3(v['MRR@10'])} & {f3(v['MRR@10_cur'])} & {f3(v['Stale@10'])} & "
                        f"{f3(v['T_MRR@10_cur'])} & {f3(v['T_Hit@10_cur'])} \\\\")
        if key == "full (graph + time)":
            rows.append("\\midrule")
    lines.append("\\newcommand{\\ResAblRows}{" + "\n".join(rows) + "}")

    if ans:
        lr = []
        for a in ans["answers"]:
            name = a["setting"].replace("Qwen3-4B", "").replace(", ", "").replace("+ ", "").strip() or "no retrieval"
            lr.append(f"{name} & {f3(a['citation_acc'])} & {f3(a['correct'])} & {f3(a['change_notice_temporal'])} & "
                      f"{f3(a['correct_refusals_oos'])} \\\\")
        lines.append("\\newcommand{\\ResLlmRows}{" + "\n".join(lr) + "}")
        lines.append(M("ResNAns", f"{ans['n_stable'] + ans['n_temporal'] + ans['n_out_of_scope']}"))
        al = ans.get("alignment_audit", {})
        lines.append(M("ResAlignAcc", f3(al.get("accuracy"))))
    else:
        lines.append("\\newcommand{\\ResLlmRows}{-- & -- & -- & -- & -- \\\\}")
        lines.append(M("ResNAns", "--"))
        lines.append(M("ResAlignAcc", "--"))

    if tt:
        tr = []
        for key, lab in [("static", "static RAG"), ("extended_no_time", "no time signals"), ("lexgraph", "LexGraph-VN")]:
            d = tt[key]
            tr.append(f"{lab} & {f3(d['before']['Hit@10'])} & {f3(d['after']['Hit@10'])} & {f3(d['correct_at_both_dates@10'])} \\\\")
        lines.append("\\newcommand{\\ResTtRows}{" + "\n".join(tr) + "}")
        lines.append(M("ResNTt", f"{tt['n_questions']:,}"))
    else:
        lines.append("\\newcommand{\\ResTtRows}{-- & -- & -- & -- \\\\}")
        lines.append(M("ResNTt", "--"))
    lines.append("\\newcommand{\\ResFindings}{(to be written from the final numbers)}")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
