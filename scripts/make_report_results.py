"""Write docs/progress_report/results.tex (LaTeX macros) from the metrics of run finetune_v1_20261123.

Standard library only, so it runs locally after `rsync`ing outputs/runs/ back from the server.
Missing results fall back to the base-model numbers (marked in the generated file) so the report always compiles.

Usage: python3 scripts/make_report_results.py --run outputs/runs/finetune_v1_20261123 --out docs/progress_report/results.tex
"""

import argparse
import json
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="outputs/runs/finetune_v1_20261123")
    ap.add_argument("--ce-train", default="data/train/ce_train.json")
    ap.add_argument("--out", default="docs/progress_report/results.tex")
    # final system (version alignment v2): metrics of the runs under outputs/runs/align_v2_20261123 and notices_v2_20261123
    ap.add_argument("--ft", default=None, help="eval_pipeline metrics dir of the final system")
    ap.add_argument("--answers", default=None, help="eval_answers metrics.json of the final system")
    ap.add_argument("--timetravel", default=None, help="eval_timetravel timetravel.json of the final system")
    ap.add_argument("--align", default=None, help="figdata_v2.json of version alignment v2")
    args = ap.parse_args()
    run = Path(args.run)
    base = load(run / "eval_base/metrics/results.json")
    # time signals only (no graph signals) when available, else the full evaluation
    ft_dir = "eval_ft_nograph" if (run / "eval_ft_nograph/metrics/results.json").exists() else "eval_ft"
    ft_metrics = Path(args.ft) if args.ft else run / ft_dir / "metrics"
    ft = load(ft_metrics / "results.json")
    ans = load(args.answers or run / "eval_answers/metrics/metrics.json")
    tt = load(args.timetravel or run / "eval_timetravel/metrics/timetravel.json")
    al2 = load(args.align) if args.align else None
    ce = load(args.ce_train)
    notes = []
    if ft is None:
        notes.append("eval_ft missing: fine-tuned numbers fall back to base")

    def M(name, val):
        return f"\\newcommand{{\\{name}}}{{{val}}}"

    lines = ["% generated by scripts/make_report_results.py -- do not edit by hand"]
    lines += [f"% NOTE: {n}" for n in notes]
    b_ret, f_ret = base["retrieval_only_test"], (ft or base)["retrieval_only_test"]
    bv, fv = base["variants"], (ft or base)["variants"]
    lines += [M("ResZsMrr", f3(b_ret["MRR@10"])), M("ResZsRten", f3(b_ret["R@10"])),
              M("ResZsCeMrr", f3(bv["retriever + re-ranker"]["MRR@10"])), M("ResZsCeRten", f3(bv["retriever + re-ranker"]["R@10"])),
              M("ResFtMrr", f3(f_ret["MRR@10"])), M("ResFtRten", f3(f_ret["R@10"])),
              M("ResFtCeMrr", f3(fv["retriever + re-ranker"]["MRR@10"])), M("ResFtCeRten", f3(fv["retriever + re-ranker"]["R@10"]))]
    no, yes = fv["retriever + re-ranker"], fv["+ time (gamma, injection)"]
    lines += [M("ResStaleNoTime", f3(no["Stale@10"])), M("ResStaleTime", f3(yes["Stale@10"])),
              M("ResTmrrNoTime", f3(no["T_MRR@10_cur"])), M("ResTmrrTime", f3(yes["T_MRR@10_cur"])),
              M("ResThitNoTime", f3(no["T_Hit@10_cur"])), M("ResThitTime", f3(yes["T_Hit@10_cur"])),
              M("ResNTemporal", f"{(ft or base)['n_test_temporal']:,}")]
    lines += [M("ResStaleNoTimePct", f"{100 * no['Stale@10']:.0f}\\%"), M("ResStaleTimePct", f"{100 * yes['Stale@10']:.1f}\\%"),
              M("ResTimeMrr", f3(yes["MRR@10"])),
              M("ResTmrrAmends", f3(fv.get("full, amends edges only", {}).get("T_MRR@10_cur"))),
              M("ResTmrrRepl", f3(fv.get("full, replaces/repeals only", {}).get("T_MRR@10_cur")))]
    b = (ft or base)["best_val"]
    lines.append(M("ResWeights", f"$\\gamma={b['gamma']:g}$"))
    lines.append(M("ResCePairs", f"{ce['rows'] * 8:,}" if ce else "--"))

    labels = [("retriever + re-ranker", "fine-tuned retriever + re-ranker (no time signals)"),
              ("+ time (gamma, injection)", "\\quad \\textbf{+ time signals (stale penalty, successor injection)}"),
              ("full - successor injection", "\\quad + stale penalty only (no successor injection)"),
              ("full, amends edges only", "\\quad + time signals, amends edges only"),
              ("full, replaces/repeals only", "\\quad + time signals, replaces / repeals edges only")]
    rows = []
    for key, lab in labels:
        v = fv.get(key)
        if v:
            rows.append(f"{lab} & {f3(v['MRR@10'])} & {f3(v['MRR@10_cur'])} & {f3(v['Stale@10'])} & "
                        f"{f3(v['T_MRR@10_cur'])} & {f3(v['T_Hit@10_cur'])} \\\\")
        if key == "+ time (gamma, injection)":
            rows.append("\\midrule")
    lines.append("\\newcommand{\\ResAblRows}{" + "\n".join(rows) + "}")

    if ans:
        lr = []
        for a in ans["answers"]:
            name = a["setting"].replace("Qwen3-4B", "").replace(", ", "").replace("+ ", "").strip() or "no retrieval"
            lr.append(f"{name} & {f3(a['citation_acc'])} & {f3(a['correct'])} & {f3(a['change_notice_temporal'])} & "
                      f"{f3(a['correct_refusals_oos'])} \\\\")
        lines.append("\\newcommand{\\ResLlmRows}{" + "\n".join(lr) + "}")
        lines.append(M("ResNAns", f"{ans['n_stable'] + ans['n_temporal'] + ans['n_out_of_scope']}"))
        full = []
        for a_, name in zip(ans["answers"], ["no retrieval", "plain RAG", "\\textbf{time-aware RAG (ours)}"]):
            g = lambda k: f3(a_.get(k)) if a_.get(k) is not None else "--"  # noqa: E731
            full.append(f"{name} & {g('citation_acc')} & {g('correct')} & {g('correct_temporal')} & {g('faithful')} & "
                        f"{g('change_notice_recall_changed')} & {g('change_notice_false_alarm_stable')} & "
                        f"{g('correct_refusals_oos')} \\\\")
        lines.append("\\newcommand{\\ResLlmFullRows}{" + "\n".join(full) + "}")
        lines.append(M("ResNChanged", f"{ans.get('n_temporal_changed', '--')}"))
        al = ans.get("alignment_audit", {})
        lines.append(M("ResAlignAcc", f3(al.get("accuracy"))))
        lines.append(M("ResAlignAccPct", f"{100 * al.get('accuracy', 0):.0f}\\%"))
        ours = ans["answers"][-1]
        plain = ans["answers"][1]
        for k, name in [("change_notice_false_alarm_stable", "FalseAlarm"), ("change_notice_recall_changed", "NoticeRecall"),
                        ("correct", "Correct"), ("correct_temporal", "CorrectT"), ("change_notice_temporal", "NoticeT")]:
            if k in ours:
                lines.append(M(f"ResAns{name}", f3(ours[k])))
                lines.append(M(f"ResAns{name}Pct", f"{100 * ours[k]:.0f}\\%"))
        lines.append(M("ResAnsPlainCorrect", f3(plain["correct"])))
        lines.append(M("ResAnsPlainCorrectT", f3(plain["correct_temporal"])))
        lines.append(M("ResAnsNoneCorrectPct", f"{100 * ans['answers'][0]['correct']:.0f}\\%"))
    else:
        lines.append("\\newcommand{\\ResLlmRows}{-- & -- & -- & -- & -- \\\\}")
        lines.append(M("ResNAns", "--"))
        lines.append(M("ResAlignAcc", "--"))

    if tt:
        tr = []
        for key, lab in [("static", "static RAG"), ("extended_no_time", "no time signals"), ("lexgraph", "LexGraph-VN")]:
            d = tt[key]
            tr.append(f"{lab} & {f3(d['before']['Hit@10'])} & {f3(d['after']['Hit@10'])} & {f3(d['correct_at_both_dates@10'])} \\\\")
        lines.append("\\newcommand{\\ResTtRows}{" + "\n".join(tr) + "}")
        lines.append(M("ResNTt", f"{tt['n_questions']:,}"))
        lines.append(M("ResTtBothPct", f"{100 * tt['lexgraph']['correct_at_both_dates@10']:.0f}\\%"))
        lines.append(M("ResTtStaticBothPct", f"{100 * tt['static']['correct_at_both_dates@10']:.0f}\\%"))
    else:
        lines.append("\\newcommand{\\ResTtRows}{-- & -- & -- & -- \\\\}")
        lines.append(M("ResNTt", "--"))
    # ---------------- figure data
    import ast
    import csv

    def curve_from(model_dir, log, key):
        pts = []
        z = None
        if Path(log).exists():
            for line in Path(log).read_text(errors="ignore").splitlines():
                if line.startswith("zero-shot val:"):
                    try:
                        z = ast.literal_eval(line.split(":", 1)[1].strip())
                    except Exception:
                        pass
        states = sorted(Path(model_dir).glob("checkpoint-*/trainer_state.json"),
                        key=lambda q: int(q.parent.name.split("-")[1]))
        if z and key.replace("eval_", "") in z:
            pts.append((0.0, z[key.replace("eval_", "")]))
        if states:
            st = json.loads(states[-1].read_text())
            pts += [(h["epoch"], h[key]) for h in st["log_history"] if key in h]
        return pts

    bi = curve_from("outputs/models/bge-m3-legal", run / "train_bi/run.log", "eval_val_cosine_mrr@10")
    cec = curve_from("outputs/models/reranker-legal", run / "train_ce/run.log", "eval_val_mrr@10")
    lines.append(M("ResBiCurve", " ".join(f"({x:.3f},{y:.4f})" for x, y in bi) or "(0,0)"))
    lines.append(M("ResCeCurve", " ".join(f"({x:.3f},{y:.4f})" for x, y in cec) or "(0,0)"))

    grid_p = ft_metrics / "val_grid.csv" if ft else run / "eval_base/metrics/val_grid.csv"
    gm, gs = [], []
    if grid_p.exists():
        rows_g = list(csv.DictReader(grid_p.open()))
        for r in rows_g:
            if float(r["beta"]) == float(b["beta"]) and float(r["mu"]) == float(b["mu"]):
                gm.append((float(r["gamma"]), float(r["MRR@10_cur"])))
                gs.append((float(r["gamma"]), float(r["Stale@10"])))
        mu_best = {}
        for r in rows_g:
            mu_best[float(r["mu"])] = max(mu_best.get(float(r["mu"]), 0), float(r["MRR@10_cur"]))
        lines.append(M("ResMuCurve", " ".join(f"({k:g},{v:.4f})" for k, v in sorted(mu_best.items()))))
    lines.append(M("ResGammaMrr", " ".join(f"({x:g},{y:.4f})" for x, y in sorted(gm)) or "(0,0)"))
    lines.append(M("ResGammaStale", " ".join(f"({x:g},{y:.4f})" for x, y in sorted(gs)) or "(0,0)"))

    fd = load(run / "figdata.json")
    if al2:  # version alignment v2: classifier probability per (old article, successor article) pair
        mids = [round((a + c) / 2, 3) for a, c in zip(al2["prob_bins"][:-1], al2["prob_bins"][1:])]
        rej = [n - m for n, m in zip(al2["pair_prob_counts"], al2["pair_prob_counts_accepted"])]
        lines.append(M("ResAlignHistRej", " ".join(f"({m},{n})" for m, n in zip(mids, rej))))
        lines.append(M("ResAlignHistAcc", " ".join(f"({m},{n})" for m, n in zip(mids, al2["pair_prob_counts_accepted"]))))
        lines.append(M("ResAlignThr", f"{al2['threshold']:.2f}"))
        lines.append(M("ResAlignAccepted", f"{al2['n_accepted']:,}"))
        lines.append(M("ResAlignPairs", f"{al2['n_pairs']:,}"))
        lines.append(M("ResAlignArtPairs", f"{al2['n_article_pairs']:,}"))
        lines.append(M("ResAlignArtAccepted", f"{al2['n_article_pairs_accepted']:,}"))
        lines.append(M("ResAlignJudged", f"{al2['judged_pairs']:,}"))
        t2 = al2["test"]["v2_classifier_hungarian"]
        lines.append(M("ResAlignPrec", f"{t2['precision']:.2f}"))
        lines.append(M("ResAlignRec", f"{t2['recall']:.2f}"))
    elif fd:
        mids = [round((a + c) / 2, 3) for a, c in zip(fd["sim_bins"][:-1], fd["sim_bins"][1:])]
        lines.append(M("ResSimHist", " ".join(f"({m},{n})" for m, n in zip(mids, fd["sim_counts"]))))
        lines.append(M("ResSimHistExp", " ".join(f"({m},{n})" for m, n in zip(mids, fd["sim_counts_explicit"]))))
        lines.append(M("ResAlignAccepted", f"{fd['n_accepted']:,}"))
        lines.append(M("ResAlignPairs", f"{fd['n_pairs']:,}"))

    if tt:
        for key, short in [("static", "St"), ("extended_no_time", "Nt"), ("lexgraph", "Lg")]:
            d = tt[key]
            lines.append(M(f"ResTt{short}", f"(before,{d['before']['Hit@10']:.3f}) (after,{d['after']['Hit@10']:.3f}) "
                                             f"(both,{d['correct_at_both_dates@10']:.3f})"))
    else:
        for short in ["St", "Nt", "Lg"]:
            lines.append(M(f"ResTt{short}", "(before,0) (after,0) (both,0)"))
    if ans:
        for a, short in zip(ans["answers"], ["None", "Plain", "Ours"]):
            lines.append(M(f"ResAns{short}", f"(correct,{a['correct']:.3f}) (temporal,{a['correct_temporal']:.3f}) "
                                             f"(notice,{a['change_notice_temporal']:.3f}) (refuse,{a['correct_refusals_oos']:.3f})"))
    else:
        for short in ["None", "Plain", "Ours"]:
            lines.append(M(f"ResAns{short}", "(correct,0) (temporal,0) (notice,0) (refuse,0)"))
    lines.append("\\newcommand{\\ResFindings}{(to be written from the final numbers)}")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
