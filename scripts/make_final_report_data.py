"""Write docs/final_report/data.tex: LaTeX macros for the figures and tables that only the final report has
(knowledge-graph statistics, baselines on split v2, alignment features, change-notice trade-off, crawl evaluation).

Inputs are small JSON / CSV files copied from the server into outputs/final_report_data/ (see the file names below);
the main results macros come from scripts/make_report_results.py (docs/final_report/results.tex).

Usage: python3 scripts/make_final_report_data.py
"""

import argparse
import json
from pathlib import Path


def load(p):
    p = Path(p)
    return json.loads(p.read_text()) if p.exists() else None


def M(name, val):
    return f"\\newcommand{{\\{name}}}{{{val}}}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="outputs/final_report_data")
    ap.add_argument("--baselines", default="outputs/runs/baselines_v2_20261124/metrics")
    ap.add_argument("--out", default="docs/final_report/data.tex")
    args = ap.parse_args()
    d = Path(args.data)
    L = ["% generated by scripts/make_final_report_data.py -- do not edit by hand"]

    # ---------------- knowledge graph
    kg = load(d / "data_kg_kg_stats.json")
    names = {"based_on": "based on", "cites": "cites", "repeals": "repeals", "guides": "guides", "replaces": "replaces",
             "amends": "amends", "partially_repeals": "part.\\ repeals", "suspends": "suspends", "interprets": "interprets"}
    et = sorted(kg["edge_types"].items(), key=lambda x: -x[1])
    L.append(M("KgEdgeSyms", ",".join(k.replace("_", "") for k, _ in et)))
    L.append(M("KgEdgeLabels", ",".join("{" + names[k] + "}" for k, _ in et)))
    L.append(M("KgEdgeCoords", " ".join(f"({v},{k.replace('_', '')})" for k, v in et)))
    status = kg["doc_status"]
    tot = sum(status.values())
    L.append(M("KgInForcePct", f"{100 * status.get('Còn hiệu lực', 0) / tot:.1f}"))
    L.append(M("KgExpiredPct", f"{100 * (status.get('Hết hiệu lực toàn bộ', 0)) / tot:.1f}"))
    L.append(M("KgPartlyPct", f"{100 * status.get('Hết hiệu lực một phần', 0) / tot:.1f}"))
    dt = kg["doc_types"]
    for key, nm in [("Quyết định", "Decision"), ("Nghị quyết", "Resolution"), ("Thông tư", "Circular"), ("Nghị định", "Decree"),
                    ("Luật", "Law"), ("Thông tư liên tịch", "JointCircular"), ("Pháp lệnh", "Ordinance")]:
        L.append(M(f"KgType{nm}", f"{dt.get(key, 0):,}"))
    lv = kg["louvain"]
    L.append(M("KgLouvainComm", f"{lv['communities']}"))
    L.append(M("KgLouvainMod", f"{lv['modularity']:.2f}"))
    L.append(M("KgLouvainNodes", f"{lv['nodes']:,}"))
    xr = kg["xref_eval"]
    L.append(M("KgXrefP", f"{xr['precision_vs_portal_relations']:.2f}"))
    L.append(M("KgXrefR", f"{xr['recall_vs_portal_relations']:.2f}"))
    L.append(M("KgXrefNew", f"{xr['new_refs_not_in_portal']:,}"))
    L.append(M("KgArtXref", f"{kg['xref_article_edges']:,}"))
    L.append(M("KgArtXrefRes", f"{100 * kg['xref_article_resolved']:.1f}"))
    L.append(M("KgDocsWithArticles", f"{kg['docs_with_articles']:,}"))
    # most authoritative documents (HITS authorities) for the link-analysis table
    rows = []
    for k, s in enumerate(kg["top_hits_authority"][:6], start=1):
        num, title = (x.strip() for x in s.split("|", 1))
        title = title.replace(f"Nghị định số {num}", "").replace(f"Luật {num}", "").strip()
        title = (title[:58] + "…") if len(title) > 58 else title
        rows.append(f"{k} & {num} & {title} \\\\")
    L.append("\\newcommand{\\KgAuthRows}{" + "\n".join(rows) + "}")
    comm = []
    for c in kg["community_fields"][:6]:
        f = [k for k in c["top_fields"] if k != "Chưa phân loại"][:2]
        comm.append(f"{c['size']:,} & {'; '.join(f)} \\\\")
    L.append("\\newcommand{\\KgCommRows}{" + "\n".join(comm) + "}")

    # ---------------- QA data
    eda = load(d / "data_processed_v2_eda_stats.json")
    L.append(M("EdaQWords", f"{eda['query_length']['mean_words']:.1f}"))
    L.append(M("EdaPWords", f"{eda['passage_length']['mean_words']:.0f}"))
    L.append(M("EdaPWordsNinetyNine", f"{eda['passage_length']['p99_words']:.0f}"))
    L.append(M("EdaUnseen", f"{100 * eda['test_positives_unseen_in_train']:.0f}\\%"))
    ppq = eda["positives_per_query"]
    L.append(M("EdaMultiGold", f"{100 * (1 - ppq['1'] / sum(ppq.values())):.1f}\\%"))

    # ---------------- baselines on split v2
    b = Path(args.baselines)
    rows = []
    zs = next(iter(sorted((b / "zs").glob("dense_*_test.json"))), None)
    ft = next(iter(sorted((b / "ft").glob("dense_*_test.json"))), None)
    for f, name in [("bm25_syllable_test.json", "BM25 (syllables)"), ("bm25_pyvi_test.json", "BM25 (pyvi words)"),
                    ("dense_vietnamese-bi-encoder_test.json", "vietnamese-bi-encoder"),
                    (zs, "BGE-M3 (zero-shot)"), (ft, "BGE-M3 (fine-tuned)")]:
        if f is None:
            continue
        m = load(f if isinstance(f, Path) else b / f)
        if m:
            r = m.get("metrics", m)
            rows.append(f"{name} & {r['MRR@10']:.3f} & {r['Recall@10']:.3f} & {r['Recall@100']:.3f} \\\\")
    L.append("\\newcommand{\\BaseRows}{" + "\n".join(rows) + "}")

    # ---------------- version alignment
    al = load(d / "data_kg_temporal_alignment_v2.json")
    nice = {"sim": "bi-encoder similarity", "tok_jacc": "token overlap", "ce": "cross-encoder score", "rank": "candidate rank",
            "head_jacc": "heading overlap", "len_ratio": "length ratio", "art_dist": "article-number distance",
            "rel_repeals": "relation: repeals", "clause_op": "clause-level amendment", "rel_replaces": "relation: replaces"}
    imp = [(k, v) for k, v in al["permutation_importance"].items() if k in nice][:8]
    L.append(M("AlFeatSyms", ",".join(k.replace("_", "") for k, _ in imp)))
    L.append(M("AlFeatLabels", ",".join("{" + nice[k] + "}" for k, _ in imp)))
    L.append(M("AlFeatCoords", " ".join(f"({max(v, 0):.4f},{k.replace('_', '')})" for k, v in imp)))
    t = al["test"]["v2_classifier_hungarian"]
    c = al["test"]["v2_classifier"]
    L.append(M("AlTestAcc", f"{t['accuracy']:.2f}"))
    L.append(M("AlTestF", f"{t['f1']:.2f}"))
    L.append(M("AlClsP", f"{c['precision']:.2f}"))
    L.append(M("AlClsR", f"{c['recall']:.2f}"))
    L.append(M("AlPosRate", f"{100 * al['positive_rate']:.0f}\\%"))
    s = al["split_sizes"]
    L.append(M("AlSplits", f"{s['train']:,} / {s['val']:,} / {s['test']:,}"))

    # ---------------- change-notice trade-off on validation (Jaccard threshold x LLM check)
    ng = load(d / "outputs_runs_notices_v2_20261123_tune_llm_v2_notice_gate.json")
    for mode, nm in [(None, "None"), ("fast", "Fast"), ("think", "Think")]:
        pts = [(g["false_alarm_stable"], g["recall_changed"], g["jaccard_below"]) for g in ng["grid"]
               if g.get("llm_check") == mode and (g["delta"] is None or g["delta"] > 100)]
        pts.sort(key=lambda x: x[2])
        L.append(M(f"Notice{nm}", " ".join(f"({100 * fa:.1f},{100 * r:.1f})" for fa, r, _ in pts)))
    L.append(M("NoticeNChanged", f"{ng['n_temporal_changed']}"))

    # ---------------- crawl
    pe = load(d / "data_crawl_parser_eval.json")
    rows = []
    for k, nm in [("so_ky_hieu", "document number"), ("title", "title"), ("loai_van_ban", "document type"),
                  ("co_quan_ban_hanh", "issuing body"), ("ngay_ban_hanh", "issue date"), ("ngay_co_hieu_luc", "effective date"),
                  ("ngay_het_hieu_luc", "expiry date"), ("tinh_trang_hieu_luc", "validity status"),
                  ("articles_same_count", "number of articles")]:
        rows.append(f"{nm} & {100 * pe[k]['accuracy']:.1f} & {pe[k]['n']} \\\\")
    L.append("\\newcommand{\\ParserRows}{" + "\n".join(rows) + "}")
    L.append(M("ParserDocs", f"{pe['documents']}"))
    rk = load(d / "data_crawl_relations_known.json")["evaluation_vs_portal"]
    rows = []
    for k, nm in [("any_type", "any type"), ("based_on", "based on"), ("succession_edges", "succession"),
                  ("expiry_edges", "replaces / repeals")]:
        r = rk[k]
        rows.append(f"{nm} & {r['precision']:.2f} & {r['recall']:.2f} & {r['gold']} \\\\")
    L.append("\\newcommand{\\RelRows}{" + "\n".join(rows) + "}")
    pn = load(d / "data_crawl_pages_new.json")
    up = load(d / "data_kg_live_update_stats.json")
    L.append(M("CrawlFetched", f"{pn['fetched'] + pn['cached']:,}"))
    L.append(M("CrawlParsed", f"{pn['parsed']:,}"))
    L.append(M("CrawlBlocked", f"{pn['robots_blocked']}"))
    for k, nm in [("new_documents", "NewDocs"), ("new_articles", "NewArts"), ("new_edges", "NewEdges"),
                  ("new_amendment_ops", "NewOps"), ("older_documents_closed", "Closed"), ("new_chunks", "NewChunks"),
                  ("new_alignments_accepted", "NewAlign"), ("affected_qa_passages", "Affected")]:
        L.append(M(f"Live{nm}", f"{up[k]:,}"))
    am = load(d / "data_kg_amendments.json")
    L.append(M("AmOps", f"{am['operations']:,}"))
    L.append(M("AmDocs", f"{am['documents_with_ops']:,}"))
    L.append(M("AmResolved", f"{100 * am['target_resolved']:.1f}"))
    L.append(M("AmArtFound", f"{100 * am['target_article_found']:.1f}"))
    ops = am["op_types"]
    L.append(M("AmOpCoords", " ".join(f"({v},{{{k}}})" for k, v in sorted(ops.items(), key=lambda x: -x[1]) if k != "Thay")))

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
